# Converts the tibiamaps.io markers.json into data/minimap_markers.lua for the minimap.
# Download https://tibiamaps.github.io/tibia-map-data/markers.json, then run:
#   python tibiamaps_markers.py markers.json ../../data/minimap_markers.lua
import sys, json

# order of /images/game/minimap/flag0..flag19
ICONS = ['checkmark', '?', '!', 'star', 'crossmark', 'cross', 'mouth', 'spear', 'sword', 'flag',
         'lock', 'bag', 'skull', '$', 'red up', 'red down', 'red right', 'red left', 'up', 'down']

def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '') + '"'

markers = json.load(open(sys.argv[1], encoding='utf-8'))
out = ['-- generated by tools/minimap/tibiamaps_markers.py from tibiamaps.io markers.json',
       '-- {x, y, z, icon, description}', 'return {']
for m in markers:
    icon = ICONS.index(m['icon'])
    out.append('{%d,%d,%d,%d,%s},' % (m['x'], m['y'], m['z'], icon, lua_str(m.get('description', ''))))
out.append('}')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(markers), 'markers')
